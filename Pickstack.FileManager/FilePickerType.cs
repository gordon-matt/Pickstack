namespace Pickstack.FileManager;

/// <summary>
/// Specifies the file picker type.
/// </summary>
public enum FilePickerType
{
    /// <summary>
    /// The any value.
    /// </summary>
    Any,
    /// <summary>
    /// The file value.
    /// </summary>
    File,
    /// <summary>
    /// The image value.
    /// </summary>
    Image,
    /// <summary>
    /// The media value.
    /// </summary>
    Media,
    /// <summary>
    /// The folder value.
    /// </summary>
    Folder
}